export function countryName(code: string | undefined): string | undefined {
  return code ? COUNTRY_NAMES_FR[code.trim().toUpperCase()] : undefined;
}

export function countryFlag(code: string): string {
  const upper = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) return "";
  return String.fromCodePoint(...[...upper].map((letter) => 0x1f1e6 + letter.charCodeAt(0) - 65));
}

/** All countries sorted by their French name, accents ignored. */
export function sortedCountries(): { code: string; name: string }[] {
  return Object.entries(COUNTRY_NAMES_FR)
    .map(([code, name]) => ({ code, name }))
    .sort((left, right) => left.name.localeCompare(right.name, "fr", { sensitivity: "base" }));
}

/** Countries whose French name or code matches the typed text, accents ignored. */
export function searchCountries(query: string): { code: string; name: string }[] {
  const wanted = simplify(query);
  if (!wanted) return sortedCountries();
  const matches = sortedCountries().filter((country) => simplify(country.name).includes(wanted) || country.code.toLowerCase() === wanted);
  // Names starting with the text come first: « f » shows France before Afghanistan.
  const starts = (country: { name: string }) => (simplify(country.name).startsWith(wanted) ? 0 : 1);
  return matches.sort((left, right) => starts(left) - starts(right));
}

function simplify(value: string): string {
  return value.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();
}
