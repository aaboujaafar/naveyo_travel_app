// Regenerates src/modules/country-info/data.ts from Wikidata (CC0):
//   node scripts/build-country-info.mjs
// Plug types (P2853), mains voltage (P2884), driving side (P1622), currency (P38/P498),
// calling code (P474). Calling codes are cross-checked with mledoze/countries.
import { readFileSync, writeFileSync } from "node:fs";

const headers = { Accept: "application/sparql-results+json", "User-Agent": "NaveyoBuild/1.0 (country info)" };
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
// One query at a time, waiting when Wikidata asks to slow down.
const sparql = async (query) => {
  for (let attempt = 0; attempt < 5; attempt += 1) {
    const response = await fetch(`https://query.wikidata.org/sparql?query=${encodeURIComponent(query)}`, { headers });
    if (response.ok) return (await response.json()).results.bindings;
    if (response.status !== 429 && response.status < 500) throw new Error(`Wikidata ${response.status}`);
    await pause(Number(response.headers.get("retry-after") ?? 10) * 1000 * (attempt + 1));
  }
  throw new Error("Wikidata unavailable");
};
const byIso = (rows) => {
  const map = new Map();
  for (const row of rows) map.set(row.iso.value, [...(map.get(row.iso.value) ?? []), row.v.value]);
  return map;
};
const PLUG_TYPES = {
  Europlug: "C", Schuko: "F", "Type E": "E", "BS 1363": "G", "BS 546": "D", "NEMA 1-15": "A", "NEMA 5-15": "B",
  "AS/NZS 3112": "I", "SN 441011": "J", "IEC 60906-1": "N", "Type H": "H", "Type K": "K", "Type L": "L",
};
const SIDES = { Q14565199: "right", Q11920728: "left", Q13196750: "left" };

const plugs = await sparql("SELECT ?iso ?v WHERE { ?c wdt:P297 ?iso ; wdt:P2853 ?v . }");
const plugNames = await sparql('SELECT ?p ?l WHERE { ?c wdt:P2853 ?p . ?p rdfs:label ?l . FILTER(LANG(?l)="en") }');
const volts = await sparql("SELECT ?iso ?v WHERE { ?c wdt:P297 ?iso ; p:P2884/psv:P2884/wikibase:quantityAmount ?v . }");
const sides = await sparql("SELECT ?iso ?v WHERE { ?c wdt:P297 ?iso ; wdt:P1622 ?v . }");
const currencies = await sparql("SELECT ?iso ?v WHERE { ?c wdt:P297 ?iso ; wdt:P38 ?x . ?x wdt:P498 ?v . }");
const calls = await sparql("SELECT ?iso ?v WHERE { ?c wdt:P297 ?iso ; wdt:P474 ?v . }");
const names = new Map(plugNames.map((row) => [row.p.value, row.l.value]));
const mledoze = await (await fetch("https://raw.githubusercontent.com/mledoze/countries/master/countries.json")).json();
const expectedCall = new Map(mledoze.map((country) => [country.cca2, country.idd?.suffixes?.length === 1 ? `${country.idd.root}${country.idd.suffixes[0]}` : country.idd?.root]));

const codes = readFileSync(new URL("../src/modules/countries/index.ts", import.meta.url), "utf8").match(/^ {2}([A-Z]{2}):/gm).map((line) => line.trim().slice(0, 2));
const plugMap = byIso(plugs), voltMap = byIso(volts), sideMap = byIso(sides), currencyMap = byIso(currencies), callMap = byIso(calls);
const info = {};
for (const code of codes) {
  const types = [...new Set((plugMap.get(code) ?? []).map((uri) => PLUG_TYPES[names.get(uri)]).filter(Boolean))].sort();
  const voltages = [...new Set((voltMap.get(code) ?? []).map(Number).filter((volt) => volt >= 100 && volt <= 240))].sort((a, b) => a - b);
  const side = [...new Set((sideMap.get(code) ?? []).map((uri) => SIDES[uri.split("/").pop()]).filter(Boolean))];
  const currency = [...new Set((currencyMap.get(code) ?? []).filter((value) => /^[A-Z]{3}$/.test(value)))].sort();
  // Keep the calling code that agrees with mledoze/countries when Wikidata lists several.
  const call = (callMap.get(code) ?? []).map((value) => value.replace(/\s+/g, "")).filter((value) => /^\+\d{1,4}$/.test(value));
  const expected = expectedCall.get(code);
  const callingCode = call.length === 1 ? call[0] : call.find((value) => expected && value.startsWith(expected)) ?? (expected && /^\+\d+$/.test(expected) ? expected : undefined);
  info[code] = {
    ...(types.length ? { plugs: types } : {}),
    ...(voltages.length ? { voltage: voltages } : {}),
    ...(side.length === 1 ? { drives: side[0] } : {}),
    ...(currency.length ? { currencies: currency } : {}),
    ...(callingCode ? { callingCode } : {}),
  };
}
const today = new Date().toISOString().slice(0, 10);
writeFileSync(new URL("../src/modules/country-info/data.ts", import.meta.url), `// Generated by scripts/build-country-info.mjs — do not edit by hand.
// Source: Wikidata (CC0), ${today}; calling codes cross-checked with mledoze/countries.
import type { CountryInfo } from ".";

export const COUNTRY_INFO_UPDATED_ON = "${today}";

export const COUNTRY_INFO: Record<string, CountryInfo> = ${JSON.stringify(info)};
`);
console.log(`${Object.keys(info).length} countries, ${Object.values(info).filter((item) => item.plugs).length} with plugs, ${Object.values(info).filter((item) => item.drives).length} with a driving side`);
