// Regenerates src/modules/entry-requirements/matrix-data.ts from the dataset:
//   node scripts/build-entry-matrix.mjs
// The app also refreshes it at runtime, at most weekly; this is the offline copy.
import { writeFileSync } from "node:fs";

const csvUrl = "https://raw.githubusercontent.com/imorte/passport-index-data/main/passport-index-matrix-iso2.csv";
const commitsUrl = "https://api.github.com/repos/imorte/passport-index-data/commits?path=passport-index-matrix-iso2.csv&per_page=1";
const codes = { "-1": "-", "visa free": "F", "visa on arrival": "A", "e-visa": "E", eta: "T", "visa required": "R", "no admission": "N" };
const encode = (raw) => (/^\d+$/.test(raw.trim()) ? raw.trim() : codes[raw.trim().toLowerCase()] ?? "?");

const [csv, commits] = await Promise.all([
  fetch(csvUrl).then((response) => response.text()),
  fetch(commitsUrl, { headers: { "User-Agent": "naveyo-build" } }).then((response) => response.json()),
]);
const updatedOn = String(commits?.[0]?.commit?.committer?.date ?? new Date().toISOString()).slice(0, 10);
const lines = csv.split(/\r?\n/).filter((line) => line.trim());
const header = lines[0].split(",").map((cell) => cell.trim().toUpperCase());
const passports = [];
const rows = [];
for (const line of lines.slice(1)) {
  const cells = line.split(",");
  if (cells.length !== header.length) continue;
  passports.push(cells[0].trim().toUpperCase());
  rows.push(cells.slice(1).map(encode).join(","));
}
const file = `// Generated by scripts/build-entry-matrix.mjs — do not edit by hand.
// Source: imorte/passport-index-data (MIT licence), data of ${updatedOn}.
import type { EntryMatrix } from "./matrix";

export const BUNDLED_MATRIX: EntryMatrix = ${JSON.stringify({ updatedOn, passports, destinations: header.slice(1), rows })};
`;
writeFileSync(new URL("../src/modules/entry-requirements/matrix-data.ts", import.meta.url), file);
console.log(`${passports.length} passports × ${header.length - 1} destinations, data of ${updatedOn}, ${Math.round(file.length / 1024)} KB`);
